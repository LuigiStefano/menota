-- Esquema inicial da Entrega 1. Idempotente; não altera tabelas preexistentes.
CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(30) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL
);
-- Entrega 2: acréscimo idempotente, preservando usuários, registros e suas chaves.
CREATE TABLE IF NOT EXISTS resumos (
    id UUID PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    inicio DATE NOT NULL,
    fim DATE NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL,
    texto_cifrado TEXT NOT NULL,
    fontes_json TEXT NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    configuracao VARCHAR(100) NOT NULL,
    assinatura VARCHAR(64) NOT NULL,
    CONSTRAINT resumo_sem_duplicacao UNIQUE (usuario_id, inicio, fim, assinatura)
);
CREATE TABLE IF NOT EXISTS registros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    data DATE NOT NULL,
    texto_cifrado TEXT NOT NULL,
    versao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT um_registro_por_dia UNIQUE (usuario_id, data)
);
